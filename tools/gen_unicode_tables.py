#!/usr/bin/env python3
"""Regenerates server/unicode_tables.hpp from Python's unicodedata.

The tokenizer's pre-tokenization pattern needs the general categories L
(letter), M (mark) and N (number). Usage: tools/gen_unicode_tables.py > server/unicode_tables.hpp
"""
import sys
import unicodedata


def ranges(kind):
    result, start = [], None
    for code in range(0x110000):
        inside = unicodedata.category(chr(code))[0] == kind
        if inside and start is None:
            start = code
        elif not inside and start is not None:
            result.append((start, code - 1))
            start = None
    if start is not None:
        result.append((start, 0x10FFFF))
    return result


def main():
    out = sys.stdout
    out.write('#pragma once\n// Generated by tools/gen_unicode_tables.py from Unicode %s. Do not edit.\n'
              % unicodedata.unidata_version)
    out.write('#include <cstdint>\n\nnamespace tidal::server::unicode_tables {\n'
              'struct Range { uint32_t first, last; };\n')
    for kind, name in [('L', 'letters'), ('M', 'marks'), ('N', 'numbers')]:
        items = ranges(kind)
        out.write('inline constexpr Range %s[] = {\n' % name)
        for i in range(0, len(items), 6):
            out.write('    ' + ' '.join('{0x%X,0x%X},' % pair for pair in items[i:i + 6]) + '\n')
        out.write('};\n')
    out.write('} // namespace tidal::server::unicode_tables\n')


if __name__ == '__main__':
    main()
